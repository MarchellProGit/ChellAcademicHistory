    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        BarangController cb = new BarangController();
        ManageBarangView mb = new ManageBarangView();
        
        String a = this.txtNamaBarang.getText();
        String b = this.cmbKategoriBarang.getSelectedItem().toString();     
        int c = Integer.parseInt(this.txtStok.getText());
        int d = Integer.parseInt(this.txtStokMinimum.getText());
        double e = Double.parseDouble(this.txtHarga.getText());
        
        boolean status = cb.tambahData(a, b, c, d, e);
        if (status == true) {
            mb.tampil();
            JOptionPane.showMessageDialog(this, "Berhasil Tambah Data");
            
            this.txtNamaBarang.setText("");
            this.cmbKategoriBarang.setSelectedIndex(0);
            this.txtStok.setText("");
            this.txtStokMinimum.setText("");
            this.txtHarga.setText("");
        } else {
            JOptionPane.showMessageDialog(this, "Gagal Tambah Data");
        }
        
    }//GEN-LAST:event_jButton1ActionPerformed


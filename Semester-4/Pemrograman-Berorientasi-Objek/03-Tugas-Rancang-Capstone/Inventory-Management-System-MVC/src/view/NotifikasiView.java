    public void tampilkanNotifikasi() {
        dtm = (DefaultTableModel) tblNotifikasi.getModel();
        dtm.setRowCount(0);  // Reset tabel sebelum menambah data

        // Ambil data notifikasi dari controller dan masukkan ke dalam tabel
        try (ResultSet res = ctr.getNotifikasi()) {
            while (res.next()) {
                dtm.addRow(new Object[] {
                    res.getInt("id_notifikasi"),
                    res.getInt("id_barang"),
                    res.getString("pesan"),
                    res.getString("status"),
                    res.getTimestamp("tanggal_notifikasi")
                });
            }
        } catch (SQLException e) {
            e.printStackTrace();
        }
    }

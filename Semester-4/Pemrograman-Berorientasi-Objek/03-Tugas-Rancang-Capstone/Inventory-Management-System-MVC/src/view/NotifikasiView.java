    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        //tombol detail : Ambil ID dari tabel dan tampilkan detail
        int selectedRow = tblNotifikasi.getSelectedRow();
        if (selectedRow != -1) {
            int idNotifikasi = (Integer) tblNotifikasi.getValueAt(selectedRow, 0);
            int idBarang = (Integer) tblNotifikasi.getValueAt(selectedRow, 1);
            String pesan = (String) tblNotifikasi.getValueAt(selectedRow, 2);
            String status = (String) tblNotifikasi.getValueAt(selectedRow, 3);
            Timestamp tanggalNotifikasi = (Timestamp) tblNotifikasi.getValueAt(selectedRow, 4);

            // Menampilkan detail barang dengan ID
            JOptionPane.showMessageDialog(this, "Barang ID: " + idBarang + "\nNotifikasi ID: " + idNotifikasi + 
                "\nPesan: " + pesan + "\nStatus: " + status + "\nTanggal: " + tanggalNotifikasi);
        }
    }//GEN-LAST:event_jButton1ActionPerformed


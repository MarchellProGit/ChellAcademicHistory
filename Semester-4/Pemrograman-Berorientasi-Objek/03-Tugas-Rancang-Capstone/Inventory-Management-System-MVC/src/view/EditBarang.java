    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        BarangController bc = new BarangController();
        ManageBarangView mb = new ManageBarangView();
        
        int a = Integer.parseInt(this.lblUid.getText());
        String b = this.txtUnama.getText();
        String c = this.cmbUkategori.getSelectedItem().toString();
        int d = Integer.parseInt(this.txtUstok.getText());
        double e = Double.parseDouble(this.txtUharga.getText());
        
        boolean status = bc.ubahData(a, b, c, d, e);
        if (status == true) {
            mb.tampil();
            JOptionPane.showMessageDialog(this, "Berhasil Ubah Data");
            
            this.lblUid.setText("");
            this.txtUnama.setText("");
            this.cmbUkategori.setSelectedIndex(0);
            this.txtUstok.setText("");
            this.txtUharga.setText("");
        } else {
            JOptionPane.showMessageDialog(this, "Gagal Ubah Data");
        }
    }//GEN-LAST:event_jButton1ActionPerformed


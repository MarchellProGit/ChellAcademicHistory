    private void btnTambahTransaksiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTambahTransaksiActionPerformed
        // TODO add your handling code here:
        try {
            int idBarang = Integer.parseInt(txtIDBarang.getText());
            String jenis = cboxJenisTransaksi.getSelectedItem().toString();
            int jumlah = Integer.parseInt(txtJumlahBarang.getText());
            String dateString = jfieldTanggal.getText();
            String keterangan = txtKeterangan.getText();

            // Parse the date string using SimpleDateFormat
            Timestamp tanggal;
            try {
                SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd HH:mm:ss");
                java.util.Date utilDate = sdf.parse(dateString);
                tanggal = new Timestamp(utilDate.getTime());
            } catch (ParseException e) {
                JOptionPane.showMessageDialog(this, "Tanggal tidak valid. Format yang benar: yyyy-MM-dd HH:mm:ss", "Error", JOptionPane.ERROR_MESSAGE);
                return;  // Exit the method if parsing fails
            }

            TransaksiController tc = new TransaksiController();
            String resultMessage = tc.prosesTambahData(idBarang, jenis, jumlah, tanggal, keterangan);
            JOptionPane.showMessageDialog(this, resultMessage);
            DefaultTableModel dtm = tc.buatTabel();
            this.tblTambahBarang.setModel(dtm);
            tc.tampilkanData();

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Input tidak valid: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_btnTambahTransaksiActionPerformed

    private void jfieldTanggalActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jfieldTanggalActionPerformed
        // Get the value entered in the JFormattedTextField
        String dateString = jfieldTanggal.getText().trim();  // Trim any whitespace around the input

        // Validate the entered date
        try {
            SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd HH:mm:ss");
            sdf.setLenient(false);  // Ensure strict parsing of the date format
            java.util.Date utilDate = sdf.parse(dateString);  // Parse the string into a Date

            // Optional: Display a success message
            JOptionPane.showMessageDialog(this, "Tanggal valid: " + dateString, "Info", JOptionPane.INFORMATION_MESSAGE);
        } catch (ParseException e) {
            // Show error message if the date format is incorrect
            JOptionPane.showMessageDialog(this, "Tanggal tidak valid. Format yang benar: yyyy-MM-dd HH:mm:ss", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jfieldTanggalActionPerformed


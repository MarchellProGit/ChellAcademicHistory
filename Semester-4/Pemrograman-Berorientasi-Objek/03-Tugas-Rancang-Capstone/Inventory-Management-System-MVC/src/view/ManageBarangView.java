    private void tblBarangMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblBarangMouseClicked
        // TODO add your handling code here:
        DefaultTableModel dtm = (DefaultTableModel) this.tblBarang.getModel();
        
        int pilih = this.tblBarang.getSelectedRow();
        
        if (pilih != -1) {
            Uid = dtm.getValueAt(pilih, 0).toString();
            Uname = dtm.getValueAt(pilih, 1).toString();
            Ukategori = dtm.getValueAt(pilih, 2).toString();
            Ustok = dtm.getValueAt(pilih, 3).toString();
            //Ustokmin = dtm.getValueAt(pilih, 4).toString();
            Uharga = dtm.getValueAt(pilih, 5).toString();
            
           
        } else {
            JOptionPane.showMessageDialog(this, "Pilih baris terlebih dulu!");
        }
    }//GEN-LAST:event_tblBarangMouseClicked

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        //memeriksa apakah ada baris yang dipilih
        if (Uid == null) {
            JOptionPane.showMessageDialog(this, "Pilih baris terlebih dahulu!");
        return;
        }
        
        EditBarang edt = new EditBarang();
        edt.setIsi(Uid, Uname, Ukategori, Ustok, Uharga);
        edt.setVisible(true);
        this.setVisible(false);
    }//GEN-LAST:event_jButton2ActionPerformed

